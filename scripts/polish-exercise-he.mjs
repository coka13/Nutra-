for (const [id, row] of Object.entries(rows)) {
  const sourceName = (sourceNames.get(id) || '').toLowerCase();
  let name = row.nameHe.replace(/^תרגיל כושר:\s*/, '');
  for (const [phrase, replacement] of Object.entries(phrases).sort(
    (a, b) => b[0].length - a[0].length,
  ))
    name = name.replace(
      new RegExp('\\b' + phrase.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '\\b', 'gi'),
      replacement,
    );
  name = name.replace(
    /[a-zA-Z][a-zA-Z'-]*/g,
    (word) =>
      words[word.toLowerCase()] ??
      word
        .split('-')
        .map((part) => words[part.toLowerCase()] ?? part)
        .join('-'),
  );
  name = name.replace(/מוט W/g, 'מוט מסולסל');
  name = name
    .replace(/מכבש ספסל|לחיצת ספסל/g, 'לחיצת חזה')
    .replace(/להקות/g, 'רצועות')
    .replace(/עגלים/g, 'שוקיים')
    .replace(/\s+/g, ' ')
    .trim();
  // A curl is a joint movement, not always an elbow curl. Preserve the exercised joint.
  const joint = /(?:leg|hamstring).*curl/.test(sourceName)
    ? 'ברכיים'
    : /wrist.*curl/.test(sourceName)
      ? 'שורש כף היד'
      : undefined;
  if (joint) {
    name = name.replace(/כפיפת מרפקים/g, 'כפיפת ' + joint);
    row.instructionsHe = row.instructionsHe.replace(/כפיפת מרפקים/g, 'כפיפת ' + joint);
  }
  row.instructionsHe = row.instructionsHe.replace(/להקות/g, 'רצועות');
  row.nameHe = overrides[id] || name;
}
const remaining = Object.entries(rows).filter(([, row]) => /[a-z]/i.test(row.nameHe));
