function segment(text: string): string {
  const key = text.trim().toLowerCase();
  if (PHRASES[key]) return PHRASES[key];
  if (!LATIN.test(text)) return measures(text.trim());
  // "can (12 fl oz)", "pizza (12" dia)": translate the head, then the sizes in brackets.
  const bracket = text.match(/^([^()]*?)\s*(\(.*\))\s*(.*)$/);
  if (bracket && bracket[1]) {
    const [, head, inner, rest] = bracket;
    const parts = [...inner.matchAll(/\(([^()]*(?:\([^()]*\)[^()]*)*)\)/g)].map(
      (m) => `(${translateList(m[1])})`,
    );
    return [segment(head), ...parts, rest ? segment(rest) : ''].filter(Boolean).join(' ');
  }
  // Leading count or size: "10 chips", "2-1/4" dia".
  const sized = measures(text);
  if (sized !== text && !LATIN.test(sized.replace(/\b[A-Z][\w'’.-]*/g, ''))) return sized;
  // "Wendy's salad", "Stouffer's meal": keep the brand, translate the noun.
  for (const noun of Object.keys(BRAND_NOUNS).sort((a, b) => b.length - a.length)) {
    const m = text.match(new RegExp(`^(.+?) ${noun.replace(/[()]/g, '\\$&')}$`, 'i'));
    if (m && /^[A-Z0-9"]/.test(m[1])) return `${BRAND_NOUNS[noun]} ${m[1]}`;
  }
  // "scoop EAS Whey": unit first, then the brand.
  const lead = text.match(/^(scoop\/packet|scoop|packet) ([A-Z].*)$/);
  if (lead) return `${PHRASES[lead[1]]} ${lead[2]}`;
  // "small drumstick", "large neck": size word + known noun.
  const size = text.match(/^(small|medium|large|extra large|miniature|mini|regular)\s+(.+)$/i);
  if (size && PHRASES[size[2].toLowerCase()]) {
    const sizeHe = { small: 'קטן', medium: 'בינוני', large: 'גדול', 'extra large': 'גדול במיוחד', miniature: 'מיני', mini: 'מיני', regular: 'רגיל' }[
      size[1].toLowerCase() as 'small'
    ];
    return `${PHRASES[size[2].toLowerCase()]} ${sizeHe}`;
  }
  return sized;
}

/** Splits on commas outside brackets. */
function splitTop(text: string) {
  const parts: string[] = [];
  let depth = 0,
    start = 0;
  for (let i = 0; i < text.length; i++) {
    if (text[i] === '(') depth++;
    else if (text[i] === ')') depth = Math.max(0, depth - 1);
    else if (text[i] === ',' && depth === 0) {
      parts.push(text.slice(start, i));
      start = i + 1;
    }
  }
  parts.push(text.slice(start));
  return parts.map((part) => part.trim()).filter(Boolean);
}

/** Comma-separated parts ("cup, cooked, diced"), trying longer known runs first. */
function translateList(text: string): string {
  const whole = text.trim().toLowerCase();
  if (PHRASES[whole]) return PHRASES[whole];
  const parts = splitTop(text);
  const out: string[] = [];
  for (let i = 0; i < parts.length; ) {
    let j = parts.length;
    for (; j > i + 1; j--) if (PHRASES[parts.slice(i, j).join(', ').toLowerCase()]) break;
    out.push(segment(parts.slice(i, j).join(', ')));
    i = j;
  }
  return out.join(', ');
}

/** Hebrew label for a USDA portion description. */
export function hebrewUnitName(en: string): string {
  const text = en
    .trim()
    // USDA labels were cut at 80 characters; restore the common endings.
    .replace(/\(yield after cooking, bone (?:a|and skin r)[^)]*$/, '(yield after cooking, bone and skin removed)')
    .replace(/\(yield after cooking, bone r[^)]*$/, '(yield after cooking, bone removed)')
    .replace(/\(([^()]*)$/, '($1)');
  const result = translateList(text)
    .replace(/\s+/g, ' ')
    .replace(/\(\s+/g, '(')
    .replace(/\s+\)/g, ')')
    .trim();
  // Only a product name is left: say what it is in Hebrew and keep the name.
  return HEBREW.test(result) ? result : `יחידת ${result}`;
}

/**
 * The Hebrew label to store for a USDA unit: the curated translation when it is complete,
 * otherwise a machine translation if that one is real Hebrew.
 */
export function pickHebrewUnit(en: string, machine?: string | null) {
  const curated = hebrewUnitName(en);
  if (PHRASES[en.trim().toLowerCase()] || !looksEnglish(curated)) return curated;
  return machine && !looksEnglish(machine) ? machine : curated;
}

/** True when a label still reads as English (ignoring brand names written with a capital). */
export function looksEnglish(he: string) {
  return !HEBREW.test(he) || /\b[a-z]{2,}\b/.test(he.replace(/\b[A-Z][\w'’.!-]*/g, ''));
}
